#!/usr/bin/env python3
"""Original choir-like startup cue: editable score -> MIDI, WAV and Flash PCM.

Only the Python standard library is needed. No sampled voices, soundfont or
runtime MIDI synthesizer. GM Voice Oohs is a hint for external MIDI players;
the device/WAV use our own additive, detuned vowel synthesis instead.
"""
import argparse
import json
import math
from pathlib import Path
import struct
import wave

ROOT = Path(__file__).resolve().parents[1]


def load_score(path=ROOT / "data/startup-score.json"):
    score = json.loads(path.read_text(encoding="utf-8"))
    if score["sample_rate"] != 16000 or not 500 <= score["duration_ms"] <= 4000:
        raise ValueError("Use 16 kHz and a 500..4000 ms startup cue")
    if not 0 <= score["program"] <= 127 or not 1 <= len(score["notes"]) <= 32:
        raise ValueError("Use a MIDI program 0..127 and one to 32 notes")
    for note in score["notes"]:
        if not (48 <= note["midi"] <= 96 and 1 <= note["velocity"] <= 127
                and note["start_ms"] >= 0 and note["duration_ms"] >= 80
                and note["start_ms"] + note["duration_ms"] <= score["duration_ms"] - 400):
            raise ValueError("Notes must fit with 400 ms for release and silent tail")
    return score


def render(score):
    rate = score["sample_rate"]
    signal = [0.0] * (rate * score["duration_ms"] // 1000)
    # Three slightly detuned singers, soft 'ooh' harmonics and slow vibrato.
    for note in score["notes"]:
        start = rate * note["start_ms"] // 1000
        sustain = note["duration_ms"] / 1000
        length = int((sustain + 0.18) * rate)
        hz = 440 * 2 ** ((note["midi"] - 69) / 12)
        for singer, cents in enumerate((-7, 0, 7)):
            frequency = hz * 2 ** (cents / 1200)
            for index in range(length):
                t = index / rate
                attack = min(1.0, t / 0.055)
                release = max(0.0, 1 - max(0.0, t - sustain) / 0.18)
                envelope = math.sin(attack * math.pi / 2) ** 2 * release ** 2
                phase = 2 * math.pi * frequency * t + singer * 0.43
                phase += 0.18 * math.sin(2 * math.pi * (4.7 + singer * 0.3) * t)
                vowel = (math.sin(phase) + 0.35 * math.sin(2 * phase)
                         + 0.16 * math.sin(3 * phase) + 0.055 * math.sin(5 * phase))
                signal[start + index] += vowel * envelope * note["velocity"] / 127 / 3
    # Two quiet early reflections; no feedback or random input.
    dry = signal[:]
    for delay_ms, gain in ((47, 0.14), (83, 0.09)):
        delay = rate * delay_ms // 1000
        for index in range(delay, len(signal)):
            signal[index] += dry[index - delay] * gain
    peak = max(abs(value) for value in signal)
    # -9 dBFS peak headroom; final 120 ms is explicit silence for DMA draining.
    result = [round(value / peak * 11600) for value in signal]
    result[-rate * 120 // 1000:] = [0] * (rate * 120 // 1000)
    return result


def vlq(number):
    result = [number & 127]
    while number >> 7:
        number >>= 7
        result.insert(0, (number & 127) | 128)
    return bytes(result)


def midi_bytes(score):
    # 480 ticks/quarter, 500000 us/quarter: 960 ticks per second.
    title = score["title"].encode("utf-8")
    events = [(0, b"\xff\x03" + vlq(len(title)) + title),
              (0, b"\xff\x51\x03\x07\xa1\x20"),
              (0, bytes((0xC0, score["program"])))]
    for note in score["notes"]:
        start = round(note["start_ms"] * 0.96)
        end = round((note["start_ms"] + note["duration_ms"]) * 0.96)
        events.extend(((start, bytes((0x90, note["midi"], note["velocity"]))),
                       (end, bytes((0x80, note["midi"], 0)))))
    events.append((round(score["duration_ms"] * 0.96), b"\xff\x2f\x00"))
    track = bytearray()
    previous = 0
    for tick, event in sorted(events, key=lambda item: item[0]):
        track.extend(vlq(tick - previous) + event)
        previous = tick
    return b"MThd" + struct.pack(">IHHH", 6, 0, 1, 480) + b"MTrk" + struct.pack(">I", len(track)) + track


def header_text(score, samples):
    lines = ["// Generated by tools/gen_startup_sound.py; edit data/startup-score.json.",
             "#pragma once", "#include <stdint.h>",
             f"#define STARTUP_SOUND_RATE {score['sample_rate']}u",
             f"#define STARTUP_SOUND_SAMPLES {len(samples)}u",
             "static const int16_t startup_sound_pcm[STARTUP_SOUND_SAMPLES] = {"]
    lines.extend("    " + ", ".join(map(str, samples[i:i + 16])) + ","
                 for i in range(0, len(samples), 16))
    return "\n".join(lines) + "\n};\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=ROOT / "assets/music")
    parser.add_argument("--header", type=Path, default=ROOT / "main/startup_sound_data.h")
    args = parser.parse_args()
    score = load_score()
    samples = render(score)
    args.output_dir.mkdir(parents=True, exist_ok=True)
    (args.output_dir / "startup.mid").write_bytes(midi_bytes(score))
    with wave.open(str(args.output_dir / "startup.wav"), "wb") as wav:
        wav.setparams((1, 2, score["sample_rate"], 0, "NONE", "not compressed"))
        wav.writeframes(struct.pack(f"<{len(samples)}h", *samples))
    args.header.write_text(header_text(score, samples), encoding="utf-8", newline="\n")
    print(f"Startup sound: {len(samples) / score['sample_rate']:.2f}s; {len(samples) * 2} Flash bytes")


if __name__ == "__main__":
    main()
