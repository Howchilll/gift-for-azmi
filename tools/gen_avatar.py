#!/usr/bin/env python3
"""Pack the generated full-color cartoon into a Flash-resident RGB565 image.

Sizing and format conversion only; the actual illustration uses imagegen.
Usage: python tools/gen_avatar.py [source.png]
"""
from pathlib import Path
import sys
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SIDE = 144


def main():
    source = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "assets/images/azmi-cartoon-v2.png"
    artwork = Image.open(source).convert("RGB").resize((SIDE, SIDE), Image.Resampling.LANCZOS)
    data = bytearray()
    for r, g, b in artwork.getdata():
        pixel = ((r & 248) << 8) | ((g & 252) << 3) | (b >> 3)
        data.extend(pixel.to_bytes(2, "little"))
    rows = [", ".join(f"0x{v:02x}" for v in data[i:i + 24]) for i in range(0, len(data), 24)]
    header = "\n".join([
        "// Generated by tools/gen_avatar.py; full-color cartoon stored in Flash.",
        "#pragma once", '#include "lvgl.h"', f"#define AVATAR_SIDE {SIDE}",
        "static const uint8_t AZMI_AVATAR_PIXELS[] = {",
        *("    " + row + "," for row in rows), "};",
        "static const lv_image_dsc_t AZMI_AVATAR_IMAGE = {",
        "    .header = {.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565,",
        f"               .w = {SIDE}, .h = {SIDE}, .stride = {SIDE * 2}}},",
        "    .data_size = sizeof(AZMI_AVATAR_PIXELS), .data = AZMI_AVATAR_PIXELS,", "};", "",
    ])
    (ROOT / "main/avatar_data.h").write_text(header, encoding="utf-8", newline="\n")
    print(f"Avatar: {SIDE}x{SIDE}, {len(data)} Flash bytes, no mutable portrait buffer")


if __name__ == "__main__":
    main()
